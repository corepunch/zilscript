-- Story and companion regressions.
local Walk = require("tests.story_walk")
local walk = Walk.new("books.pocket-weather.pocket-weather", 97)
local function says(command, fragment)
  local reply = walk.game:resume(command)
  assert(reply:find(fragment, 1, true), command .. " printed: " .. reply)
end

says("push bell", "corner of the blank")
says("search bell", "tucked under the bell's base")
says("north", "Warm Tile Terrace")
says("climb down ladder", "lowest tiles")
assert(walk.env.HERE == walk.env.TERRACE)
says("climb up ladder", "Weathercock Perch")
assert(walk.env.HERE == walk.env.VANE_DECK)
says("climb up ladder", "top rung")
assert(walk.env.HERE == walk.env.VANE_DECK)
says("climb down ladder", "Warm Tile Terrace")
assert(walk.env.HERE == walk.env.TERRACE)
says("south", "Dispatch Post")
says("south", "Folded Yesterday Archive")
says("open box", "folded report")
says("take report", "Taken.")
says("close report", "folded tight")
says("north", "Dispatch Post")
says("west", "Steam Kitchen")
says("steam report over kettle", "fold uncurls")
says("read report", "pressed flower")
says("close report", "like butterfly wings")
assert(not walk.env.FSETQ(walk.env.REPORT, walk.env.OPENBIT), "closure is physical")
says("open report", "The report still remembers")
assert(walk.env.FSETQ(walk.env.REPORT, walk.env.OPENBIT), "reopening exposes the flower")
says("take spoon", "Taken.")
says("wave spoon", "orchestra of puddings")
says("west", "Pocket Laundry")
says("search apron", "tumble free")
says("take ribbon", "Taken.")
says("wear ribbon", "grand belt")
says("wave ribbon", "sheep-shaped cloud")
says("pull lines", "tiny slap")
says("take button", "Taken.")
says("north", "Button Rookery")
says("search nests", "Aster is watching")
says("give button to rook", "fair exchange")
says("search nests", "Aster is out on the perch")
assert(walk.env.LOC(walk.env.RIBBON) == walk.env.ADVENTURER, "pretend wearing did not consume the ribbon")
says("east", "Weathercock Perch")
says("down", "Warm Tile Terrace")
says("north", "Whisper Arch")
says("wrap ribbon around clapper", "CLANG becomes tok")
assert(walk.env.LOC(walk.env.RIBBON) == walk.env.CHIME)
says("untie spoon from clapper", "Only the ribbon")
assert(walk.env.LOC(walk.env.RIBBON) == walk.env.CHIME, "an unrelated item cannot unpad the chime")
says("untie clapper from ribbon", "take it back")
assert(walk.env.LOC(walk.env.RIBBON) == walk.env.ADVENTURER)
says("tie clapper to ribbon", "CLANG becomes tok")
says("take ribbon from chime", "take it back")
assert(walk.env.LOC(walk.env.RIBBON) == walk.env.ADVENTURER)
print("ok - Pocket Weather object play and ladder regressions")

local second = Walk.new("books.pocket-weather.pocket-weather", 97)
second:command("north")
assert(second:command("climb short ladder"):find("Weathercock Perch", 1, true))
assert(second:command("climb down short ladder"):find("Warm Tile Terrace", 1, true))
