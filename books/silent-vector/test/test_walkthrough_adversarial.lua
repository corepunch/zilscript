local runtime = require("zilscript.runtime")
local env = runtime.create_game_env()
assert(runtime.init(env, true))
env.require("zilscript")
assert(runtime.load_modules(env, { "books.silent-vector.silent-vector" }, { silent = true }))
local game = runtime.create_game(env, true)
game:start()
local function command(input, expect)
  local reply = game:resume(input)
  assert(reply and reply:find(expect, 1, true), input .. ": " .. tostring(reply))
end

command("turn breaker", "no dial")
assert(not env.POWER, "Turning a push-reset switch does not energize the system")
command("north", "pressure interlock holds")
command("reset frame", "no obvious one")
assert(not env.POWER, "Reset does not act on the wrong noun")
command("reset breaker", "breaker catches")
assert(env.POWER, "The hint's literal RESET BREAKER works")
command("reset breaker", "Already reset")
command("north", "Habitat Junction")
command("up", "Launch Cupola")
command("turn beacon", "fired by a straight push")
assert(not env.EVAC, "Beacon flavor does not arm departure")
command("down", "Habitat Junction")
command("down", "Service Spine")
command("east", "Receive Relay")
command("smell bus", "Ozone")
command("north", "Receiver Vault")
command("close receiver", "live latch")
command("kick receiver", "isolation point is in the relay")
command("open receiver", "live housing cannot be opened")
assert(not env.ISOLATED, "Flavor verbs cannot bypass physical isolation")
assert(env.LOC(env.WAFER) == env.RECEIVER, "Wafer remains in the receiver")
print("Silent Vector: literal reset, wrong-tool detours and safe new interactions pass")
