assert(env.KEY_WOUND, "The heart is actually wound")
game:resume("position soldier")
assert(env.COMPANION_COUNT == 2, "One placed toy and Nutmeg contribute once")
game:resume("position music box")
assert(env.GAME_WON, "The repaired route reaches an ending")
assert(#failures == 0, table.concat(failures, "\n"))
print("Wondertown round 2 link verbs: ok")
