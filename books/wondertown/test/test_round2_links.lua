-- Numeric-link play needs each book-owned action on the affected object.
local runtime = require("zilscript.runtime")
local env = runtime.create_game_env()
assert(runtime.init(env, true))
env.require("zilscript")
assert(runtime.load_modules(env, { "books.wondertown.wondertown" }, { silent = true }))
local game = runtime.create_game(env, true)
local opening = game:start()
assert(opening:find("You are Pip", 1, true), "Opening introduces the player")
assert(opening:find("before dawn", 1, true), "Opening explains the immediate goal")
local failures = {}
local function hasVerb(name, verb, inventory, expected)
	if expected == nil then expected = true end
	local found = false
	local function visit(items)
		for _, item in ipairs(items) do
			if item[1] == name then
				for _, offered in ipairs(item[2]) do if offered == verb then found = true end end
			end
			visit(item[3] or {})
		end
	end
	visit(game:resume(inventory and "inventory-items" or "room-items"))
	if found ~= expected then table.insert(failures, name .. (expected and " must offer " or " must not offer ") .. verb) end
end
hasVerb("rusty ladder mechanism", "OIL")
hasVerb("folding loft ladder", "OIL")
hasVerb("folding loft ladder", "CLIMB")
hasVerb("old cuckoo clock", "THROUGH")
game:resume("east")
hasVerb("painted wooden nutcracker", "WIND")
game:resume("take key")
game:resume("wind nutcracker")
game:resume("up")
game:resume("open case")
game:resume("take soldier")
game:resume("take music box")
game:resume("take button")
hasVerb("tin soldier", "PLACE-HEART", true)
hasVerb("silver music box", "WIND", true)
hasVerb("silver music box", "PLACE-HEART", true)
hasVerb("spare button", "GIVE-TO", true)
game:resume("down")
game:resume("west")
game:resume("look under workbench")
game:resume("take can")
game:resume("climb loft ladder")
assert(env.HERE == env.WORKSHOP_FLOOR, "Dry ladder keeps its gate closed")
game:resume("lubricate mechanism")
assert(env.LADDER_OILED, "Lubricating the ladder changes its actual gate")
game:resume("climb loft ladder")
assert(env.HERE == env.STORAGE_LOFT, "Oiled ladder can be climbed through its own action")
hasVerb("old cuckoo clock", "WIND")
game:resume("open cardboard box")
game:resume("take arm")
hasVerb("porcelain doll arm", "PLACE-HEART", true)
game:resume("down")
game:resume("north")
game:resume("east")
hasVerb("brass winding mechanism", "WIND")
game:resume("east")
game:resume("take scarf")
hasVerb("red wool scarf", "GIVE-TO", true)
game:resume("west")
game:resume("south")
hasVerb("scrap-metal cart", "OPEN", false, false)
game:resume("examine piles")
game:resume("take head")
hasVerb("porcelain doll head", "GIVE-TO", true)
game:resume("give head to cart")
assert(env.CART_MOVED, "Giving the head opens the actual gate")
game:resume("east")
game:resume("take yarn")
hasVerb("ball of yarn", "GIVE-TO", true)
game:resume("give scarf to fox")
game:resume("take workshop key")
game:resume("west")
game:resume("north")
game:resume("west")
game:resume("south")
game:resume("up")
local clockOpening = game:resume("wind clock")
assert(clockOpening:find("workshop floor", 1, true), "Clock opening explains where the study entrance is")
game:resume("down")
game:resume("enter clock")
assert(env.HERE == env.TOLLIVER_STUDY, "Opening the clock provides its own enter action")
