-- Story and companion regressions.
local Walk = require("tests.story_walk")
local walk = Walk.new("books.wondertown.wondertown", 97)
local function says(command, fragment)
  local reply = walk.game:resume(command)
  assert(reply:find(fragment, 1, true), command .. " printed: " .. reply)
end

says("listen to hook", "familiar hum")
says("climb workbench", "workbench leg")
says("play with sailboat", "imaginary sea")
says("listen to train", "whistle small enough")
says("knock on duck", "wooden cluck")
says("down", "Grandfather")
says("north", "narrow alley")
says("play with snow", "very small snowman")
says("east", "Clock Square")
says("east", "quiet corner")
local old_score = walk.env.SCORE
says("open envelope", "My dear Pip")
assert(walk.env.LETTER_READ and walk.env.SCORE == old_score + 3, "opening reveals the clue once")
says("read letter", "My dear Pip")
assert(walk.env.SCORE == old_score + 3, "rereading does not score again")
says("west", "Clock Square")
says("south", "scrap-yard")
says("close cart", "rails, but no lid")
assert(walk.env.FSETQ(walk.env.SCRAP_CART, walk.env.OPENBIT), "the cart always has an open bed")
says("search piles", "with painted eyes")
says("give head to doll", "needs to pick up")
assert(not walk.env.CART_MOVED and walk.env.LOC(walk.env.DOLL_HEAD) == walk.env.SCRAP_YARD)
says("take head", "Taken.")
says("fit head on doll", "revealing the iron gate")
assert(walk.env.CART_MOVED and walk.env.LOC(walk.env.DOLL_HEAD) == walk.env.SCRAP_CART)
says("east", "snug little den")
assert(walk.env.HERE == walk.env.FOX_DEN)
print("ok - Wondertown object play, envelope and alternate cart solution")
