local Hero = require("books.de.blackout-at-meridian.test.hero")

local h = Hero.new()
h:force(100)
h:expect("klopf ans Fenster", "völlig aus dem Takt")
h:expect("schau hinter die Einsatztafel", "vergilbtes Foto")
h:expect("untersuche die Ausgangstür", "BRÜCKE, NORDEN")
h:expect("öffne die Ausgangstür", "erst nach, wenn du ein Profil")
h:expect("geh durch die Ausgangstür", "keinen unangemeldeten Helden")
assert(h.env.HERE == h.env.DISPATCH)
h:expect("wähle Blitz", "als Blitz an")
h:expect("öffne die Ausgangstür", "Die Tür ruckt im Wind")
assert(h.env.HERE == h.env.DISPATCH, "opening a door is not walking through it")
h:expect("geh durch die Ausgangstür", "Meridian-Brücke")
h:expect("klopfe an den Wagen", "zwei rasche Schläge")
h:expect("nimm die Bahn", "einfach hochzureißen wäre zu riskant")
assert(#h.reports == 0 and not h:state().rescued, "taking a tram is not a rescue roll")
h:expect("höre die Schienen", "Ticken wandert durch den Stahl")
h:expect("rieche das Kabel", "nach heißem Gummi")
h:send("rette die Fahrgäste")
h:expect("klopfe an die Straßenbahn", "klappert noch ein Haltegriff")
h:expect("ost", "Betonhalle")
h:expect("schau unter die Drohne", "ein zweites Auge")
h:force(1)
local before = h:state()
h:expect("schlag das Pult mit der Drohne", "Hebel")
h:expect("öffne das Pult", "Handhebel")
assert(h:state().health == before.health and h:state().drone == before.drone, "inspection or an indirect-object drone does not start combat")
h:send("deaktiviere das Pult")
local bruised = h:state()
h:expect("öffne den Kasten", "Das Siegel bleibt heil")
h:expect("schau in den Kasten", "Das Siegel bleibt heil")
local inspected = h:state()
assert(not inspected.boosted and inspected.health == bruised.health and inspected.karma == bruised.karma,
	"opening or inspecting the kit must not heal or spend Karma")
h:expect("benutze den Kasten", "Du erholst dich um 10 Gesundheit")
assert(h:state().boosted and h:state().karma == bruised.karma - 10)
h:expect("öffne den Kasten", "offen und leer")
h:force(100)
h:send("schlag die Drohne")
h:expect("schau unter die Drohne", "NUR BEI TROCKENEM WETTER BETREIBEN")
h:expect("ziehe den Hebel", "ENDE: DIE LICHTER VON MERIDIAN")
assert(not h:running())
print("ok - Stromausfall in Meridian scene interactions and explicit action costs")
