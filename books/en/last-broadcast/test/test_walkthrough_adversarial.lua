local runtime = require("zilscript.runtime")
local env = runtime.create_game_env()
assert(runtime.init(env, true))
env.require("zilscript")
assert(runtime.load_modules(env, { "books.en.last-broadcast.last-broadcast" }, { silent = true }))
local game = runtime.create_game(env, true)
game:start()
local function command(input, expect)
  local reply = game:resume(input)
  assert(reply and reply:find(expect, 1, true), input .. ": " .. tostring(reply))
end

command("cross breakwater", "step back")
assert(env.HERE == env.LB_LANDING, "The gale must not move the player")
command("north", "appeal board")
command("wear coats", "need their oilskin")
command("west", "station kitchen")
command("search medical bag", "bloodied dressing")
assert(env.FSETQ(env.LB_BAG, env.OPENBIT), "Searching opens the bag")
assert(env.LOC(env.LB_DRESSING) == env.LB_BAG, "Searching must not take the dressing")
command("search bag", "bloodied dressing")
command("take it", "Taken")
assert(env.LOC(env.LB_DRESSING) == env.WINNER, "The revealed dressing supports IT")
command("search bag", "nothing else from tonight")
assert(not env.LB_EDITH_CLEARED, "A search alone does not corroborate the witness")
command("examine dressing", "initials R.B.")
command("show dressing to edith", "Ruth Bell")
assert(env.LB_EDITH_CLEARED, "Normal evidence comparison still clears Edith")
print("Last Broadcast: storm, borrowed coats, and medical-bag search/IT detour pass")
