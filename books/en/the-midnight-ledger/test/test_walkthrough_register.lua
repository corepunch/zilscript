local Walk = require("tests.link_walk")
local w = Walk.new("books.en.the-midnight-ledger.the-midnight-ledger")
local e = w.env
local function step(command, expected)
    local out = w.game:resume(command)
    assert(type(out) == "string" and out:match("%S"), command)
    if expected then assert(out:find(expected, 1, true), command .. ": " .. out) end
end
step("north", "hearing chamber")
step("north", "public registry")
step("ask orr about register", "Read the times for yourself")
assert(not e.REG_READ, "a witness pointing at unsigned evidence does not establish it")
step("open register", "11:55")
assert(e.REG_READ)
step("ask orr about register", "missing key")
step("ask orr about sleeve", "Valuations")
step("close register", "wet pages begin to stick")
step("search register", "12:06")
step("south", "hearing chamber")
step("turn panel", "WHEN is blank")
step("west", "weigh room")
step("look under scale", "spring settles")
assert(not e.SCALE_SEEN)
step("search scale", "eleven pounds lighter")
assert(e.SCALE_SEEN and not e.CASE_READY)
step("turn clock", "no dial")
print("Midnight Ledger: register testimony and natural evidence actions pass")
