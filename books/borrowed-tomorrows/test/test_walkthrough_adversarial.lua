local runtime = require("zilscript.runtime")
local env = runtime.create_game_env()
assert(runtime.init(env, true))
env.require("zilscript")
assert(runtime.load_modules(env, { "books.borrowed-tomorrows.borrowed-tomorrows" }, { silent = true }))
local game = runtime.create_game(env, true)
game:start()
local function command(input, expect)
  local reply = game:resume(input)
  assert(reply and reply:find(expect, 1, true), input .. ": " .. tostring(reply))
end

command("open cabinet", "lies a tomorrow leaf")
command("take leaf from cabinet", "records your name")
assert(env.ON_LOAN and env.LOC(env.LEAF) == env.WINNER)
command("close cabinet", "sound of a book closing")
command("hint", "loan receipt")
command("east", "Folding Room")
command("put leaf under board", "You keep hold of it")
assert(env.LOC(env.LEAF) == env.WINNER, "Under the board must not lose the leaf")
command("unfold leaf", "width of your arms")
command("north", "Reading Terrace")
command("clip leaf in frame", "Both clips hold")
command("score", "one day ready to share")
command("hint", "Read from the reading frame")
command("listen to frame", "taking a breath to speak")
command("take leaf from frame", "catch the page before the wind does")
assert(env.LOC(env.LEAF) == env.WINNER, "Unclipping must retrieve the actual leaf")
assert(not env.PUBLISHED_LOAN, "Unclipping does not publish")
command("read leaf", "The word stays here")
command("clip leaf to frame", "Both clips hold")
command("unclip frame", "catch the page before the wind does")
assert(env.LOC(env.LEAF) == env.WINNER and not env.PUBLISHED_LOAN)
command("put leaf in frame", "Both clips hold")
command("read frame", "THE END -- ROOM FOR EVERY NAME")
assert(env.PUBLISHED_LOAN, "Reading from the mounted frame publishes")
print("Borrowed Tomorrows: state-aware hints and safe clip/under-board detours pass")
