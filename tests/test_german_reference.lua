-- Diagnostic target until German ZIL support is established.
local runtime = require("zilscript.runtime")
local env = runtime.create_game_env()
assert(runtime.init(env, true), "bootstrap failed")
env.require("zilscript")
assert(runtime.load_modules(env, {"infocom.zork1-de.zork1"}, {silent=true}), "German story failed to compile/load")
local game = runtime.create_game(env, true)
local opening = game:start()
assert(type(opening) == "string" and opening:match("%S"), "German story did not start")
assert(game:is_running(), "German story stopped at startup")
local response = game:resume("inventar")
assert(type(response) == "string" and response:match("%S"), "German inventory command produced no response")
print("German startup and inventory probe passed; not a complete walkthrough")
